/**
 * API coverage report: maps every public action, lifecycle callback,
 * observation field and engine event to the example controllers that use it
 * (static scan + runtime counts from real matches) and to the tests that
 * check it. Writes docs/api-coverage.md and fails if anything is uncovered.
 *
 *   bun run coverage:api
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { ACTION_TYPES } from "@autosoccer/controller-sdk";
import { runControllerMatch } from "@autosoccer/match-runner";

const root = new URL("../", import.meta.url);
const exDir = new URL("examples/controllers/", root);
const examples = readdirSync(exDir).filter((f) => f.endsWith(".js"));
const src = Object.fromEntries(examples.map((f) => [f, readFileSync(new URL(f, exDir), "utf8")]));
const testDir = new URL("tests/", root);
const tests = Object.fromEntries(readdirSync(testDir).filter((f) => f.endsWith(".test.ts")).map((f) => [f, readFileSync(new URL(f, testDir), "utf8")]));

const LIFECYCLE = ["initialize", "update", "onMatchEnd"] as const;
const OBS_FIELDS = ["tick", "team", "attackingDirection", "period", "phase", "clock", "score", "ball", "teammates", "opponents", "restart", "events", "rejected"] as const;
const EVENTS = ["kick", "dribbleTouch", "trap", "trapMiss", "tackle", "catch", "release", "goal", "periodStart", "periodEnd", "goalScored", "ballOut", "foul", "restartAwarded", "restartTaken", "sidesSwitched"] as const;

// Runtime evidence: the featured matchup plus the API probe.
const read = (f: string) => src[f]!;
const runs = [
  await runControllerMatch({ seed: 42, blue: { source: read("blue-possession.js"), label: "blue-possession.js" }, red: { source: read("red-counter.js"), label: "red-counter.js" } }),
  await runControllerMatch({ seed: 42, blue: { source: read("api-probe.js"), label: "api-probe.js" }, red: { source: read("dumb.js"), label: "dumb.js" } }),
];
const runtimeActions: Record<string, Record<string, number>> = {};
const runtimeLifecycle: Record<string, Record<string, number>> = {};
for (const r of runs) for (const c of [r.blue, r.red]) {
  runtimeActions[c.label] = c.actionCounts;
  runtimeLifecycle[c.label] = c.lifecycleCalls;
}
const eventsSeen: Record<string, number> = {};
for (const r of runs) for (const e of r.sim.events) eventsSeen[e.event.type] = (eventsSeen[e.event.type] ?? 0) + 1;

const usedBy = (re: RegExp) => examples.filter((f) => re.test(src[f]!));
const testedBy = (re: RegExp) => Object.keys(tests).filter((f) => re.test(tests[f]!));
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const lines: string[] = [];
const missing: string[] = [];
lines.push("# Controller API coverage", "", "Generated by `bun run coverage:api` from the example controllers, the test suite and two real matches (seed 42):", "`blue-possession.js` vs `red-counter.js`, and `api-probe.js` vs `dumb.js`. Runtime counts are actions returned by each script over the full match.", "");

lines.push("## Actions (schema 1.0)", "", "| Action | Used by (examples) | Runtime count (blue-possession / red-counter / api-probe) | Tests |", "| --- | --- | --- | --- |");
for (const a of ACTION_TYPES) {
  const ex = usedBy(new RegExp(`type:\\s*"${a}"`));
  const ts = testedBy(new RegExp(`type: "${a}"|"${a}"`));
  const rc = ["blue-possession.js", "red-counter.js", "api-probe.js"].map((f) => runtimeActions[f]?.[a] ?? 0);
  if (!ex.length || !ts.length || rc[2] === 0) missing.push(`action ${a}`);
  lines.push(`| \`${a}\` | ${ex.map((f) => `\`${f}\``).join(", ")} | ${rc.join(" / ")} | ${ts.map((f) => `\`${f}\``).join(", ")} |`);
}

lines.push("", "## Lifecycle callbacks", "", "| Callback | Used by (examples) | Calls in blue-possession / red-counter / api-probe | Tests |", "| --- | --- | --- | --- |");
for (const l of LIFECYCLE) {
  const ex = usedBy(new RegExp(`\\b${l}\\s*\\(`));
  const ts = testedBy(new RegExp(`${l}`));
  const rc = ["blue-possession.js", "red-counter.js", "api-probe.js"].map((f) => runtimeLifecycle[f]?.[l] ?? 0);
  if (!ex.length || !ts.length || rc.some((x) => x === 0)) missing.push(`lifecycle ${l}`);
  lines.push(`| \`${l}\` | ${ex.map((f) => `\`${f}\``).join(", ")} | ${rc.join(" / ")} | ${ts.map((f) => `\`${f}\``).join(", ")} |`);
}

lines.push("", "## Observation fields (schema 1.0)", "", "| Field | Read by (examples) | Tests |", "| --- | --- | --- |");
for (const f of OBS_FIELDS) {
  const ex = usedBy(new RegExp(`obs\\.${esc(f)}\\b`));
  const ts = testedBy(new RegExp(`\\b${esc(f)}\\b`));
  if (!ex.length || !ts.length) missing.push(`observation field ${f}`);
  lines.push(`| \`${f}\` | ${ex.map((x) => `\`${x}\``).join(", ")} | ${ts.map((x) => `\`${x}\``).join(", ")} |`);
}

lines.push("", "## Engine events delivered to controllers (`obs.events`)", "", "| Event | Occurrences in the two matches | Handled by (examples) | Tests |", "| --- | --- | --- | --- |");
for (const e of EVENTS) {
  const ex = usedBy(new RegExp(`"${e}"`));
  const ts = testedBy(new RegExp(`"${e}"|type === "${e}"`));
  if (!ts.length) missing.push(`event ${e}`);
  lines.push(`| \`${e}\` | ${eventsSeen[e] ?? 0} | ${ex.map((x) => `\`${x}\``).join(", ") || "—"} | ${ts.map((x) => `\`${x}\``).join(", ")} |`);
}
lines.push("", missing.length ? `**Uncovered:** ${missing.join(", ")}` : "**All actions, lifecycle callbacks, observation fields and events are covered.**", "");
writeFileSync(new URL("docs/api-coverage.md", root), lines.join("\n"));
console.log(lines.join("\n"));
if (missing.length) process.exit(1);
